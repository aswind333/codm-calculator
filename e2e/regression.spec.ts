  await expect(row(page, '一等奖')).toContainText('0.096%')
  await expect(row(page, '二等奖')).toContainText('1.497%'); await expect(row(page, '二等奖')).toContainText('668.000')
  await button(page, '规则说明').click(); await button(page, '七抽转盘').click()
  await expect(page.getByText('3.125%', { exact: true })).toBeVisible()
  const faq = page.getByRole('button', { name: /最后一抽是否/ }); await faq.focus(); await page.keyboard.press('Enter'); await expect(faq).toHaveAttribute('aria-expanded', 'true')
