for (const width of [375, 430, 768, 1280, 1440]) test(`G: ${width}px 布局与控件`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 })
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  async function inspect(name: string) {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const nav = await page.locator('.site-header nav button').evaluateAll(nodes => nodes.map(n => { const r = n.getBoundingClientRect(); return [r.top, r.height] }))
    expect(new Set(nav.map(r => r[0])).size).toBe(1); expect(nav.every(r => r[1] >= 44)).toBe(true)
    const shortControls = await page.locator('button:visible, select:visible, input:visible').evaluateAll(nodes => nodes.filter(n => n.getBoundingClientRect().height < 43.9).map(n => n.outerHTML.slice(0, 120)))
    expect(shortControls).toEqual([])
    await page.screenshot({ path: info.outputPath(`${name}-${width}.png`), fullPage: true, animations: 'disabled' })
  }
  await inspect('calculator'); await button(page, '设置').click(); await inspect('prices')
  if (width < 768) {
    await page.getByLabel('编辑价格类型').selectOption('seven_draw')
    const input = page.locator('.mobile-price').getByLabel('七抽转盘（通用） 第7抽')
    await input.fill('351'); await expect(input).toHaveCSS('font-size', '16px')
    await button(page, '保存设置').click(); await expect(page.getByRole('status')).toHaveText('设置已保存')
    await button(page, '查看完整价格总表').click(); await inspect('full-table')
  } else if (width >= 1280) {
    expect(await page.locator('.price-table-wrap').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  }
  await page.getByRole('tab', { name: '初始概率' }).focus(); await page.keyboard.press('End')
  await expect(page.getByRole('tab', { name: '初始概率' })).toBeFocused(); await inspect('probabilities')
  await button(page, '规则说明').click(); await page.getByRole('button', { name: /为什么抽走不同/ }).click(); await expect(page.locator('.rules-faq [role=region]').first()).toHaveCSS('opacity', '1'); await inspect('rules')
  await page.emulateMedia({ reducedMotion: 'reduce' }); await expect(page.locator('.rules-faq [role=region]').first()).toHaveCSS('transition-duration', '0s')
  expect(errors).toEqual([])
})
