// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from '../../App'
import { createDefaultConfigs } from '../../data/defaults'
import { SETTINGS_KEY, saveSettings } from '../../storage/storage'

afterEach(() => { cleanup(); vi.restoreAllMocks() })
function memory() {
  const values = new Map<string, string>()
  return { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value) } }
}
const button = (name: string) => screen.getByRole('button', { name })
const edit = (input: HTMLElement, value: string) => fireEvent.change(input, { target: { value } })
const table = () => screen.getByRole('region', { name: '完整价格总表' })
const price = (type = '传说武器转盘', round = 1) => within(table()).getByLabelText(`${type} 第${round}抽`) as HTMLInputElement
const saveButton = () => button('保存设置') as HTMLButtonElement
async function openSettings(user: ReturnType<typeof userEvent.setup>) { await user.click(button('设置')) }
async function probabilities(user: ReturnType<typeof userEvent.setup>) { await user.click(screen.getByRole('tab', { name: '初始概率' })) }
const row = (name: string) => screen.getByRole('row', { name: new RegExp(`^${name} `) })

describe('S4 保存及主计算联动', () => {
  it('价格草稿不影响正式值；失败保留草稿；重试成功后生效并刷新恢复', async () => {
    const store = memory(); const user = userEvent.setup(); const view = render(<App storage={store} />)
    await openSettings(user); edit(price(), '30')
    const calculator = document.querySelector('#main')!
    expect(calculator.textContent).toContain('下一抽需要3 使命卡片')
    expect(store.getItem(SETTINGS_KEY)).toBeNull()
    const failure = vi.spyOn(store, 'setItem').mockImplementation(() => { throw new Error('quota') })
    await user.click(saveButton())
    expect(screen.getByRole('alert').textContent).toContain('保存失败')
    expect(price().value).toBe('30'); expect(calculator.textContent).toContain('下一抽需要3 使命卡片')
    expect(screen.queryByText('设置已保存')).toBeNull()
    failure.mockRestore(); await user.click(saveButton())
    expect(screen.getByRole('status').textContent).toBe('设置已保存')
    await user.click(button('概率计算'))
    expect(screen.getByText('下一抽需要').nextElementSibling?.textContent).toBe('30 使命卡片')
    view.unmount(); render(<App storage={store} />)
    expect(screen.getByText('下一抽需要').nextElementSibling?.textContent).toBe('30 使命卡片')
  })
  it('概率草稿隔离、保存后生效，名称单位更新但已抽ID保留，其他类型不变', async () => {
    const store = memory(); const user = userEvent.setup(); render(<App storage={store} />)
    await user.click(button('六等奖')); await openSettings(user)
    edit(within(table()).getByLabelText('传说武器转盘 单位'), 'CP')
    await probabilities(user)
    edit(screen.getByLabelText('第2等奖初始概率（%）'), '2.25')
    edit(screen.getByLabelText('第10等奖初始概率（%）'), '28')
    edit(screen.getByLabelText('第6等奖名称'), '我的奖品')
    expect(document.querySelector('#main')!.textContent).toContain('1.337%')
    expect(store.getItem(SETTINGS_KEY)).toBeNull()
    await user.click(saveButton()); await user.click(button('概率计算'))
    expect(row('二等奖').textContent).toContain('2.406%')
    expect(button('我的奖品').getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByText('下一抽需要').nextElementSibling?.textContent).toBe('5 CP')
    await user.selectOptions(screen.getByLabelText('转盘类型'), 'legendary_vehicle')
    expect(row('二等奖').textContent).toContain('1.250%')
    expect(button('六等奖').getAttribute('aria-pressed')).toBe('false')
  })
  it('标签和类型切换保留草稿，取消恢复已保存配置', async () => {
    const store = memory(); const user = userEvent.setup(); render(<App storage={store} />)
    await openSettings(user); edit(price(), '33'); await user.click(saveButton()); edit(price(), '44')
    await probabilities(user); edit(screen.getByLabelText('第1等奖名称'), '新名称')
    await user.selectOptions(screen.getByLabelText('编辑概率类型'), 'seven_draw')
    expect(screen.queryByLabelText('第8等奖名称')).toBeNull()
    edit(screen.getByLabelText('第1等奖名称'), '七抽名称')
    await user.selectOptions(screen.getByLabelText('编辑概率类型'), 'legendary_weapon')
    expect((screen.getByLabelText('第1等奖名称') as HTMLInputElement).value).toBe('新名称')
    await user.click(screen.getByRole('tab', { name: '抽奖价格' })); expect(price().value).toBe('44')
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    await user.click(button('取消修改')); expect(price().value).toBe('33')
    await probabilities(user); expect((screen.getByLabelText('第1等奖名称') as HTMLInputElement).value).toBe('一等奖')
  })
  it('恢复单行/概率仅修改草稿；全部默认必须确认且保存后才生效', async () => {
    const store = memory(); const user = userEvent.setup(); const configs = createDefaultConfigs(); configs[3].roundCosts[0] = 20; configs[3].prizes[0].weightPercent = 1.08; configs[3].prizes[9].weightPercent = 28
    saveSettings(store, configs); render(<App storage={store} />)
    const original = store.getItem(SETTINGS_KEY)
    await openSettings(user); await user.click(button('传说武器转盘 恢复默认价格'))
    expect(price().value).toBe('3'); expect(store.getItem(SETTINGS_KEY)).toBe(original)
    await probabilities(user); await user.click(button('恢复当前类型默认概率'))
    expect((screen.getByLabelText('第1等奖初始概率（%）') as HTMLInputElement).value).toBe('0.08')
    expect(store.getItem(SETTINGS_KEY)).toBe(original)
    edit(screen.getByLabelText('第1等奖名称'), '草稿名字')
    const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false)
    await user.click(button('恢复全部默认'))
    expect((screen.getByLabelText('第1等奖名称') as HTMLInputElement).value).toBe('草稿名字')
    confirm.mockReturnValue(true); await user.click(button('恢复全部默认'))
    expect(confirm).toHaveBeenCalled(); expect(store.getItem(SETTINGS_KEY)).toBe(original)
    await user.click(saveButton()); expect(JSON.parse(store.getItem(SETTINGS_KEY)!).configs).toEqual(createDefaultConfigs())
  })
  it('非法价格、权重合计、空名称禁用保存，合法0允许', async () => {
    const user = userEvent.setup(); render(<App storage={memory()} />); await openSettings(user)
    for (const value of ['', '-1', '1.5', 'abc']) { edit(price(), value); expect(saveButton().disabled).toBe(true); expect(screen.getByRole('alert')).toBeTruthy() }
    edit(price(), '0'); expect(saveButton().disabled).toBe(false)
    await probabilities(user); edit(screen.getByLabelText('第2等奖初始概率（%）'), '2')
    expect(saveButton().disabled).toBe(true)
    edit(screen.getByLabelText('第2等奖初始概率（%）'), '1.25')
    edit(screen.getByLabelText('第1等奖名称'), '')
    expect(saveButton().disabled).toBe(true)
  })
  it('站内离开可继续编辑或放弃，beforeunload仅草稿脏时启用', async () => {
    const user = userEvent.setup(); render(<App storage={memory()} />); await openSettings(user); edit(price(), '44')
    const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false)
    await user.click(button('概率计算')); expect(price().value).toBe('44')
    const event = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(event); expect(event.defaultPrevented).toBe(true)
    await probabilities(user); expect(confirm).toHaveBeenCalledTimes(1)
    confirm.mockReturnValue(true); await user.click(button('概率计算'))
    expect(screen.getByText('下一抽需要').nextElementSibling?.textContent).toBe('3 使命卡片')
    const clean = new Event('beforeunload', { cancelable: true }); window.dispatchEvent(clean); expect(clean.defaultPrevented).toBe(false)
    await openSettings(user); expect(price().value).toBe('3')
  })
  it('手机逐轮表单与桌面总表共享七/十抽草稿', async () => {
    const user = userEvent.setup(); render(<App storage={memory()} />); await openSettings(user)
    const mobile = screen.getByRole('region', { name: '手机逐轮价格编辑' })
    expect(price().closest('label')?.textContent).toBe('第1抽')
    expect(price('传说武器转盘', 10).closest('label')?.textContent).toBe('第10抽')
    expect(within(mobile).getByLabelText('传说武器转盘 第10抽').closest('label')?.textContent).toBe('第10抽')
    edit(within(mobile).getByLabelText('传说武器转盘 第10抽'), '421')
    expect(price('传说武器转盘', 10).value).toBe('421')
    await user.selectOptions(within(mobile).getByLabelText('编辑价格类型'), 'seven_draw')
    expect(within(mobile).queryByLabelText('七抽转盘（通用） 第8抽')).toBeNull()
    expect(within(table()).queryByLabelText('七抽转盘（通用） 第8抽')).toBeNull()
    edit(within(mobile).getByLabelText('七抽转盘（通用） 第7抽'), '351')
    expect(price('七抽转盘（通用）', 7).value).toBe('351')
    await user.click(button('查看完整价格总表')); expect(table().className).toContain('show-table')
    await user.click(saveButton()); await user.click(button('概率计算')); await user.selectOptions(screen.getByLabelText('转盘类型'), 'seven_draw')
    expect(screen.getByText('全抽总费用').nextElementSibling?.textContent).toBe('699 使命卡片')
  })
  it('前往规则页同样保护未保存草稿，放弃后旧配置与已抽状态保持不变', async () => {
    const store = memory(); const user = userEvent.setup(); render(<App storage={store} />)
    await user.click(button('六等奖')); await openSettings(user); edit(price('传说武器转盘', 2), '44')
    const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false)
    await user.click(button('规则说明'))
    expect(confirm).toHaveBeenCalledTimes(1)
    expect(price('传说武器转盘', 2).value).toBe('44')
    expect(screen.queryByRole('main', { name: '规则说明' })).toBeNull()
    confirm.mockReturnValue(true); await user.click(button('规则说明'))
    expect(screen.getByRole('main', { name: '规则说明' })).toBeTruthy()
    expect(store.getItem(SETTINGS_KEY)).toBeNull()
    await user.click(button('概率计算'))
    expect(button('六等奖').getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByText('下一抽需要').nextElementSibling?.textContent).toBe('5 使命卡片')
    await openSettings(user); expect(price('传说武器转盘', 2).value).toBe('5')
  })
  it('本地损坏配置安全回退并提示', () => {
    const store = memory(); store.setItem(SETTINGS_KEY, '{bad'); render(<App storage={store} />)
    expect(screen.getByRole('alert').textContent).toContain('默认配置')
    expect(screen.getByText('下一抽需要').nextElementSibling?.textContent).toBe('3 使命卡片')
  })
  it('保存零权重后保留已抽记录并显示不可计算，刷新后记录恢复', async () => {
    const store = memory(); const user = userEvent.setup(); const view = render(<App storage={store} />)
    await user.click(button('一等奖')); await openSettings(user); await probabilities(user)
    for (let i = 1; i <= 10; i++) edit(screen.getByLabelText(`第${i}等奖初始概率（%）`), i === 1 ? '100' : '0')
    await user.click(saveButton()); await user.click(button('概率计算'))
    expect(screen.getByRole('alert').textContent).toContain('剩余奖品总权重为0')
    view.unmount(); render(<App storage={store} />)
    expect(button('一等奖').getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByRole('alert').textContent).toContain('剩余奖品总权重为0')
  })
})

it('精简操作栏按真实草稿变化启用按钮，切换标签不保存或丢失修改', async () => {
  const store = memory(); const user = userEvent.setup(); render(<App storage={store} />)
  await openSettings(user)
  const disabled = () => {
    expect(saveButton().hasAttribute('disabled')).toBe(true)
    expect(button('取消修改').hasAttribute('disabled')).toBe(true)
  }
  disabled()
  expect(screen.queryByRole('heading', { name: '自定义转盘设置' })).toBeNull()
  expect(screen.queryByRole('button', { name: '返回概率计算' })).toBeNull()
  expect(screen.queryByText(/当前无未保存修改|^有未保存的?修改$/)).toBeNull()
  await user.click(price()); disabled()
  edit(price(), '30')
  expect(saveButton().hasAttribute('disabled')).toBe(false)
  expect(button('取消修改').hasAttribute('disabled')).toBe(false)
  edit(price(), '3'); disabled()
  edit(price(), '30')
  await probabilities(user)
  edit(screen.getByLabelText('第2等奖初始概率（%）'), '2.25')
  expect(saveButton().hasAttribute('disabled')).toBe(true)
  edit(screen.getByLabelText('第10等奖初始概率（%）'), '28')
  expect(saveButton().hasAttribute('disabled')).toBe(false)
  await user.click(screen.getByRole('tab', { name: '抽奖价格' }))
  expect(price().value).toBe('30')
  expect(store.getItem(SETTINGS_KEY)).toBeNull()
  await user.click(saveButton()); disabled()
  edit(price(), '40')
  vi.spyOn(window, 'confirm').mockReturnValue(true)
  await user.click(button('取消修改')); disabled()
  expect(price().value).toBe('30')
  await user.click(button('恢复全部默认'))
  expect(saveButton().hasAttribute('disabled')).toBe(false)
  await user.click(saveButton()); disabled()
})
